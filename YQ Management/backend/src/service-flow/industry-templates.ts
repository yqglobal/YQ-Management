/**
 * Industry Flow Templates — Qmova Blueprint Library
 *
 * PHILOSOPHY: These are "XL size" templates — deliberately overbuilt to cover
 * the broadest possible use case within each industry. Optional steps are
 * marked `isOptional: true`. Tenants use these as a starting point and trim
 * down to their exact workflow. They should NEVER feel like they're missing a
 * step after applying a template.
 *
 * Structure: 14 broad industry verticals. Not sub-businesses.
 * e.g., "Healthcare" covers GP, specialist, hospital, dentist, optometrist.
 *        "Food & Beverage" covers QSR, dine-in restaurant, catering, event meals.
 */

export interface StepTemplateData {
  stepOrder: number;
  name: string;
  description?: string;
  type: string;
  trigger: string;
  isOptional?: boolean;
  requiresQrScan?: boolean;
  requiresStaffAction?: boolean;
  deferredByDays?: number;
  deferredByHours?: number;
  entitlementUnit?: string;
  entitlementFormula?: string;
  entitlementFixed?: number;
  allowPartialRedemption?: boolean;
  preventDoubleRedemption?: boolean;
  customerInstruction?: string;
  staffInstruction?: string;
  locationDescription?: string;
  notifyCustomerOnActivation?: boolean;
  outcomeOptions?: string[];
  stepPrice?: number;
  isPriceVariable?: boolean;
}

