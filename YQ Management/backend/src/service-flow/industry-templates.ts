export function getTemplate(key: string): FlowTemplate | undefined {
  return INDUSTRY_TEMPLATES.find((t) => t.key === key);
}

export function getTemplatesByIndustry(industry: string): FlowTemplate[] {
  return INDUSTRY_TEMPLATES.filter(
    (t) => t.industry.toLowerCase() === industry.toLowerCase(),
  );
}

export function getTemplatesByBusinessType(type: string): FlowTemplate[] {
  return INDUSTRY_TEMPLATES.filter((t) =>
    t.businessTypes.some((b) => b.toLowerCase().includes(type.toLowerCase())),
  );
}
